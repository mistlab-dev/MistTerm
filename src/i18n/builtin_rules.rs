//! Built-in rule display names for Automation Rules (#215).
//! Conceptual keys: `rules.builtin.<id>.title` / `.hint`.
//! English `message` from pattern JSON is the fallback when an id is missing.

use eframe::egui;

struct Entry {
    title_en: &'static str,
    title_zh: &'static str,
    hint_en: &'static str,
    hint_zh: &'static str,
}

/// Localized title + hint. Falls back to `message_fallback` (usually English message).
pub fn builtin_copy(ctx: &egui::Context, id: &str, message_fallback: &str) -> (String, String) {
    let zh = crate::i18n::language(ctx) == crate::i18n::UiLanguage::Zh;
    if let Some(c) = lookup(id) {
        let title = if zh { c.title_zh } else { c.title_en };
        let hint = if zh { c.hint_zh } else { c.hint_en };
        return (title.to_string(), hint.to_string());
    }
    let fb = if message_fallback.trim().is_empty() {
        id
    } else {
        message_fallback
    };
    (fb.to_string(), String::new())
}

